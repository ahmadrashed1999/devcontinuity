import fs from 'node:fs';
import path from 'node:path';
import { clip } from '../adapters/types';
import { dataPath, ensureDir } from '../config';
import { ensureDb, prisma } from '../db';
import { ResumeContext, TaskInfo, buildResumeContext } from '../handoff/context';

export const DOC_TYPES = ['PROJECT_OVERVIEW', 'ARCHITECTURE', 'CURRENT_STATE', 'COMPLETED_TASKS', 'PENDING_TASKS', 'KNOWN_ISSUES', 'TECHNICAL_DECISIONS', 'NEXT_ACTIONS', 'GIT_STATE', 'TEST_STATUS'] as const;
export type DocType = (typeof DOC_TYPES)[number];

const when = (s: string | null | undefined) => (s ? `${s.slice(0, 16).replace('T', ' ')} UTC` : 'time not recorded');
const NONE = '_Nothing recorded. DevContinuity does not invent missing information._';

function header(title: string, ctx: ResumeContext): string[] {
  return [
    `# ${title}${ctx.project ? ` — ${ctx.project.name}` : ''}`,
    '',
    `> Generated by DevContinuity on ${when(ctx.generatedAt)} from imported agent transcripts, the project folder and Git.`,
    '> **[verified]** checked against files or Git at generation time · **[tool-confirmed]** a tool reported success inside a transcript · **[AI-reported]** claimed by an agent and not verified.',
    '',
  ];
}

function taskLine(t: TaskInfo): string {
  const tag = t.verification === 'verified' ? '[verified]' : t.verification === 'evidence_found' ? '[tool-confirmed evidence]' : t.verification === 'ai_reported' ? '[AI-reported]' : '[unverified]';
  return `- ${tag} ${clip(t.title, 220)}${t.occurredAt ? ` _(${t.occurredAt.slice(0, 10)})_` : ''}${t.source === 'agent_todo' ? ' — from the agent\'s todo list' : ''}`;
}

function taskEvidence(t: TaskInfo): string[] {
  return t.evidence.slice(0, 4).map((e) => `  - evidence (${e.type.replace(/_/g, ' ')}): ${clip(e.detail, 260)}`);
}

/** Renders the ten project knowledge documents. Pure function of the reconstructed context. */
export function renderProjectDocs(ctx: ResumeContext): Record<DocType, string> {
  const p = ctx.project;
  const repo = ctx.repo;
  const g = ctx.git;
  const out = {} as Record<DocType, string>;

  // PROJECT_OVERVIEW
  {
    const L = header('Project Overview', ctx);
    L.push('## Identity', `- Name: ${p?.name ?? 'unknown'}`, `- Repository location: ${p?.rootPath ?? 'unknown'} ${p?.pathVerified ? (p.pathExists ? '**[verified: folder exists]**' : '**[verified: folder is missing on this machine]**') : '**[not verified: no transcript recorded the working directory]**'}`, `- Git repository: ${g?.isRepo ? 'yes **[verified]**' : 'no / unavailable'}`, '');
    L.push('## Technology stack **[verified from project files]**');
    if (repo?.stack.length) for (const s of repo.stack) L.push(`- ${s.name} — ${s.evidence}`);
    else L.push(repo?.exists ? '_No known manifest files were found in the project folder._' : '_The project folder is not available, so the stack cannot be verified._');
    L.push('', '## Development history **[from imported transcripts]**', `- Sessions: ${ctx.stats.mainSessions} main, ${ctx.stats.subagentSessions} subagent`, `- Agents used: ${Object.entries(ctx.stats.agents).map(([a, n]) => `${a} (${n})`).join(', ') || 'none'}`, `- Active from ${when(ctx.stats.firstActivity)} to ${when(ctx.stats.lastActivity)}`, '');
    L.push('## Description');
    if (repo?.readmeExcerpt) L.push('From the repository README **[verified file content]**:', '', '```', repo.readmeExcerpt, '```');
    else L.push('_No README was found._');
    const summaries = ctx.knowledge.summary.filter((s) => s.source === 'ai');
    if (summaries.length) L.push('', '## AI-generated summary **[AI-reported]**', '', summaries[0].body);
    out.PROJECT_OVERVIEW = L.join('\n');
  }

  // ARCHITECTURE
  {
    const L = header('Architecture', ctx);
    if (!repo?.exists) L.push('_The project folder is not available on this machine. Nothing below could be verified._', '');
    L.push('## Top-level structure **[verified]**');
    if (repo?.topLevel.length) L.push(repo.topLevel.map((e) => `- ${e.name}${e.dir ? '/' : ''}`).join('\n'));
    else L.push(NONE);
    L.push('', '## Modules **[verified directory listing]**');
    if (repo?.modules.length) for (const m of repo.modules) L.push(`### ${m.area}/`, m.entries.map((e) => `- ${e}`).join('\n'), '');
    else L.push(NONE, '');
    L.push('## Database **[verified]**', repo?.database.length ? repo.database.map((d) => `- ${d}`).join('\n') : NONE, '');
    L.push('## API surface **[verified]**', repo?.api.length ? repo.api.map((d) => `- ${d}`).join('\n') : NONE, '');
    if (repo && Object.keys(repo.scripts).length) L.push('## Package scripts **[verified]**', Object.entries(repo.scripts).map(([k, v]) => `- \`${k}\`: \`${v}\``).join('\n'), '');
    const arch = ctx.knowledge.summary.filter((s) => /architect/i.test(s.title));
    if (arch.length) L.push('## Architecture notes **[AI-reported]**', '', arch[0].body, '');
    if (ctx.knowledge.plan.length) {
      L.push('## Plans written by agents **[AI-reported intent, not proof of implementation]**');
      for (const pl of ctx.knowledge.plan.slice(0, 5)) L.push(`### ${pl.title} _(${(pl.occurredAt ?? '').slice(0, 10)})_`, '', clip(pl.body, 3000), '');
    }
    out.ARCHITECTURE = L.join('\n');
  }

  // CURRENT_STATE
  {
    const L = header('Current State', ctx);
    const f = ctx.focus;
    L.push('## Latest session');
    if (f) {
      L.push(`- ${f.title ?? '(untitled)'} — ${f.agentLabel}, session id \`${f.externalId}\``, `- Active ${when(f.startedAt)} → ${when(f.endedAt)}${f.primaryModel ? `, model ${f.primaryModel}` : ''}`, `- Working directory: ${f.cwd ?? 'not recorded'}${f.worktree ? ` (worktree "${f.worktree}")` : ''}`, `- Branch recorded in the transcript: ${f.gitBranch ?? 'not recorded'}`, `- End state: **${f.endState.replace(/_/g, ' ')}** — ${f.endStateDetail ?? ''}`);
    } else L.push(NONE);
    L.push('', '## Last user request (verbatim)', ctx.lastUserRequest ? `_${when(ctx.lastUserRequest.at)}_\n\n\`\`\`\n${clip(ctx.lastUserRequest.text, 4000)}\n\`\`\`` : NONE);
    L.push('', '## Last assistant response **[AI-reported]**', ctx.lastAssistantResponse ? `_${when(ctx.lastAssistantResponse.at)}_\n\n\`\`\`\n${clip(ctx.lastAssistantResponse.text, 4000)}\n\`\`\`` : NONE);
    L.push('', '## Last verified action', ctx.lastVerifiedAction ? `- **[verified against Git]** ${ctx.lastVerifiedAction.description} (${when(ctx.lastVerifiedAction.at)})` : '- Nothing could be verified against Git.');
    if (ctx.lastToolConfirmedAction) L.push(`- **[tool-confirmed]** ${ctx.lastToolConfirmedAction.description} (${when(ctx.lastToolConfirmedAction.at)})${ctx.lastToolConfirmedAction.existsNow === false ? ' — the file does not exist now **[verified]**' : ''}`);
    L.push('', '## Work in progress');
    const wip = [...ctx.tasks.in_progress, ...ctx.tasks.blocked];
    L.push(wip.length ? wip.slice(0, 20).map(taskLine).join('\n') : NONE);
    L.push('', '## Task totals', Object.entries(ctx.taskCounts).map(([k, v]) => `- ${k.replace(/_/g, ' ')}: ${v}`).join('\n') || NONE);
    out.CURRENT_STATE = L.join('\n');
  }

  // COMPLETED_TASKS
  {
    const L = header('Completed Tasks', ctx);
    L.push('## Verified complete', 'Only tasks a person confirmed (or that were checked against evidence) appear here.', '');
    L.push(ctx.tasks.completed.length ? ctx.tasks.completed.map(taskLine).join('\n') : '_No task has been verified as complete yet._');
    L.push('', `## Reported complete by an agent — requires verification (${ctx.taskCounts.requires_verification ?? 0})`, 'An agent finishing its turn, or ticking its own todo list, is a claim. These stay unverified until someone checks the code, tests or Git.', '');
    if (ctx.tasks.requires_verification.length) for (const t of ctx.tasks.requires_verification) L.push(taskLine(t), ...taskEvidence(t));
    else L.push(NONE);
    if ((ctx.taskCounts.requires_verification ?? 0) > ctx.tasks.requires_verification.length) L.push('', `_Showing the ${ctx.tasks.requires_verification.length} most recent. The full list is in the DevContinuity Tasks page._`);
    out.COMPLETED_TASKS = L.join('\n');
  }

  // PENDING_TASKS
  {
    const L = header('Pending Tasks', ctx);
    const sections: [string, TaskInfo[]][] = [['In progress (the session ended before these finished)', ctx.tasks.in_progress], ['Blocked', ctx.tasks.blocked], ['Failed', ctx.tasks.failed], ['Pending', ctx.tasks.pending]];
    for (const [title, list] of sections) {
      L.push(`## ${title}`);
      if (list.length) for (const t of list) L.push(taskLine(t), ...taskEvidence(t));
      else L.push(NONE);
      L.push('');
    }
    if (ctx.tasks.cancelled.length) L.push('## Cancelled', ctx.tasks.cancelled.map(taskLine).join('\n'));
    out.PENDING_TASKS = L.join('\n');
  }

  // KNOWN_ISSUES
  {
    const L = header('Known Issues', ctx);
    L.push('## Recorded issues');
    if (ctx.knowledge.issue.length) for (const i of ctx.knowledge.issue) L.push(`### ${i.title} ${i.source === 'ai' ? '**[AI-reported]**' : `**[${i.source}]**`}`, '', clip(i.body, 1500), '');
    else L.push(NONE, '');
    L.push('## Errors at the end of the latest session **[tool-confirmed: recorded in the transcript]**');
    if (ctx.outstandingErrors.length) for (const e of ctx.outstandingErrors) L.push(`- ${when(e.at)} — ${e.toolName ?? 'error'}${e.command ? ` \`${clip(e.command, 160)}\`` : ''}`, '', '  ```', `  ${clip(e.text, 600).replace(/\n/g, '\n  ')}`, '  ```');
    else L.push(NONE);
    if (ctx.focus && ctx.focus.endState === 'api_error') L.push('', `## Session stopped by an API error`, `- ${ctx.focus.endStateDetail ?? ''}`);
    const missing = ctx.modifiedFiles.filter((f) => f.existsNow === false);
    if (missing.length) L.push('', '## Files changed by agents that no longer exist **[verified]**', missing.slice(0, 30).map((f) => `- ${f.relPath}`).join('\n'));
    out.KNOWN_ISSUES = L.join('\n');
  }

  // TECHNICAL_DECISIONS
  {
    const L = header('Technical Decisions', ctx);
    if (ctx.knowledge.decision.length) for (const d of ctx.knowledge.decision) L.push(`## ${d.title} ${d.source === 'ai' ? '**[AI-reported: extracted from transcripts]**' : `**[${d.source}]**`}`, `_${(d.occurredAt ?? '').slice(0, 10)}_`, '', clip(d.body, 2500), '');
    else L.push('_No technical decisions have been recorded. Run AI analysis on a session (Settings → Anthropic API), or add decisions manually in the Knowledge Base._', '');
    if (ctx.knowledge.memory.length) {
      L.push('## Project memory notes kept by the agent **[agent-written files, verbatim]**');
      for (const m of ctx.knowledge.memory.slice(0, 12)) L.push(`### ${m.title}`, '', clip(m.body, 2500), '');
    }
    out.TECHNICAL_DECISIONS = L.join('\n');
  }

  // NEXT_ACTIONS
  {
    const L = header('Next Actions', ctx);
    L.push('Derived mechanically from the recorded state. Each item states the fact it is based on.', '', ...ctx.nextSteps.map((s, i) => `${i + 1}. ${s}`), '', '## Limits of this reconstruction', ...ctx.caveats.map((c) => `- ${c}`));
    out.NEXT_ACTIONS = L.join('\n');
  }

  // GIT_STATE
  {
    const L = header('Git State', ctx);
    if (g?.isRepo) {
      L.push(`Captured ${when(g.capturedAt)} with read-only Git commands. **[verified]**`, '', `- Repository: ${g.repoPath}`, `- Branch: ${g.branch ?? '(detached HEAD)'}`, `- Upstream: ${g.upstream ? `${g.upstream} (ahead ${g.ahead ?? 0}, behind ${g.behind ?? 0})` : 'none configured'}`, `- Latest commit: ${g.head ? `${g.head.shortSha} — ${g.head.subject} (${g.head.author}, ${g.head.date.slice(0, 10)})` : 'no commits'}`, '');
      L.push(`## Working tree (${g.counts.total} change(s))`, `- Modified: ${g.counts.modified} · Added: ${g.counts.added} · Deleted: ${g.counts.deleted} · Renamed: ${g.counts.renamed} · Untracked: ${g.counts.untracked} · Conflicted: ${g.counts.conflicted} · Staged: ${g.counts.staged}`);
      for (const c of g.changes.slice(0, 200)) L.push(`  - ${c.kind}${c.staged ? ' (staged)' : ''}: ${c.path}`);
      if (g.changes.length > 200) L.push(`  - …and ${g.changes.length - 200} more.`);
      L.push('', '## Recent commits', g.recentCommits.map((c) => `- ${c.shortSha} ${c.date.slice(0, 10)} ${c.author}: ${c.subject}`).join('\n') || NONE);
      if (g.worktrees.length > 1) L.push('', '## Worktrees', g.worktrees.map((w) => `- ${w.path}${w.branch ? ` [${w.branch}]` : ''}`).join('\n'));
      if (g.remotes.length) L.push('', '## Remotes', g.remotes.map((r) => `- ${r.name}: ${r.url}`).join('\n'));
    } else L.push(`_Git state is not available: ${g?.error ?? 'the project folder could not be inspected'}._`);
    L.push('', '## Git operations recorded in transcripts');
    if (ctx.recordedGitOps.length) for (const o of ctx.recordedGitOps) L.push(`- ${when(o.at)} ${o.kind}${o.sha ? ` ${o.sha.slice(0, 10)}` : ''}${o.branch ? ` on ${o.branch}` : ''}${o.prUrl ? ` ${o.prUrl}` : ''} — ${o.kind === 'commit' ? (o.existsInRepo === true ? '**[verified: commit exists in the repository]**' : o.existsInRepo === false ? '**[not found in the repository now]**' : '**[tool-confirmed, not checked]**') : '**[tool-confirmed]**'}`);
    else L.push(NONE);
    L.push('', '_Historical diffs are not reconstructed. Only what Git can show now, and what tools recorded, is listed._');
    out.GIT_STATE = L.join('\n');
  }

  // TEST_STATUS
  {
    const L = header('Test Status', ctx);
    L.push('DevContinuity never executes project commands, so it did not run any tests. This lists test commands found in transcripts and their recorded outcome.', '');
    L.push('## Test infrastructure **[verified from project files]**', repo?.tests.length ? repo.tests.map((t) => `- ${t}`).join('\n') : NONE, '');
    L.push('## Test runs recorded in recent sessions **[tool-confirmed]**');
    if (ctx.testRuns.length) for (const t of ctx.testRuns) L.push(`- ${when(t.at)} \`${t.command}\` — ${t.failed === null ? 'no result recorded' : t.failed ? '**failed** (tool returned an error)' : 'tool returned without error'}`, ...(t.excerpt ? ['', '  ```', `  ${t.excerpt.replace(/\n/g, '\n  ')}`, '  ```'] : []));
    else L.push('_No test command was found in the recent transcripts._');
    L.push('', '_A passing run in an old transcript says nothing about the code as it is now. Re-run the tests._');
    out.TEST_STATUS = L.join('\n');
  }
  return out;
}

/** Regenerates and stores the knowledge documents for a project, in the database and under data/knowledge/<slug>/. */
export async function generateProjectDocs(projectId: string, ctxIn?: ResumeContext): Promise<{ docType: DocType; file: string; dir: string }[]> {
  await ensureDb();
  const ctx = ctxIn ?? (await buildResumeContext({ projectId }));
  if (!ctx.project) throw new Error('Project not found.');
  const docs = renderProjectDocs(ctx);
  const dir = ensureDir(dataPath('knowledge', ctx.project.slug));
  const db = prisma();
  const out: { docType: DocType; file: string; dir: string }[] = [];
  for (const docType of DOC_TYPES) {
    const existing = await db.knowledgeDoc.findUnique({ where: { projectId_docType: { projectId, docType } } });
    // A document someone edited by hand is theirs: it is kept, and the fresh version is written beside it.
    const manual = existing?.source === 'manual';
    const file = path.join(dir, manual ? `${docType}.generated.md` : `${docType}.md`);
    fs.writeFileSync(file, docs[docType], 'utf8');
    if (!manual) {
      await db.knowledgeDoc.upsert({ where: { projectId_docType: { projectId, docType } }, create: { projectId, docType, content: docs[docType], source: 'generated' }, update: { content: docs[docType], source: 'generated', generatedAt: new Date() } });
    }
    out.push({ docType, file, dir });
  }
  if (ctx.git) await db.project.update({ where: { id: projectId }, data: { gitState: JSON.stringify(ctx.git), gitCheckedAt: new Date(), techStack: JSON.stringify(ctx.repo?.stack ?? []) } });
  return out;
}
