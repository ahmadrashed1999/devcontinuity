export const DICT = { en, ar };
export type Dict = typeof en;

export function dict(lang: string | undefined): Dict {
  return lang === 'ar' ? ar : en;
}

const STATE_KEY: Record<string, keyof Dict> = {
  completed_turn: 'stateFinished',
  interrupted_tool: 'stateStoppedMidTool',
  interrupted_response: 'stateInterrupted',
  awaiting_assistant: 'stateNoReply',
  api_error: 'stateError',
  empty: 'stateEmpty',
  unknown: 'stateUnknown',
};
const TASK_KEY: Record<string, keyof Dict> = {
  pending: 'taskPending',
  in_progress: 'taskInProgress',
  blocked: 'taskBlocked',
  requires_verification: 'taskNeedsCheck',
  completed: 'taskCompleted',
  failed: 'taskFailed',
  cancelled: 'taskCancelled',
};

/** Human label for a session end state, in the current language. */
export function endStateLabel(t: Dict, state: string): string {
  const k = STATE_KEY[state];
  return k ? t[k] : state.replace(/_/g, ' ');
}

/** Human label for a task status, in the current language. */
export function taskStatusLabel(t: Dict, status: string): string {
  const k = TASK_KEY[status];
  return k ? t[k] : status.replace(/_/g, ' ');
}
